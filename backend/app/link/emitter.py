"""Deterministic .cypher emitter.

Given a SopIR and a LinkedIR, emits a single Cypher script of idempotent MERGE
statements that conform to the plan's graph schema.  The output is deterministic:
the same IR always produces a byte-identical script (IDs are sorted before emission).

Graph schema (see plan §3.4):
  (:Document)          -[:HAS_SECTION]->  (not emitted at this layer)
  (:Process)           -[:HAS_STEP]->      (:Step)
  (:Process)           -[:HAS_DECISION]->  (:Decision)
  (:Step)              -[:NEXT]->          (:Step | :Decision | :Terminal)
  (:Step)              -[:PERFORMED_BY]->  (:Role)
  (:Step)              -[:CONSUMES]->      (:Artifact)
  (:Step)              -[:PRODUCES]->      (:Artifact)
  (:Step)              -[:USES]->          (:System)
  (:Step)              -[:DERIVED_FROM]->  (:Clause)
  (:Decision)          -[:DERIVED_FROM]->  (:Clause)
  (:Process)           -[:HANDS_OFF_TO]->  (:Process)
"""

from __future__ import annotations

import hashlib
import json

from app.schemas.graph import LinkedIR
from app.schemas.ir_sop import SopIR


def _q(value: object) -> str:
    """Escape and quote a value as a Cypher string literal."""
    return json.dumps(str(value))


def _props(**kwargs: object) -> str:
    """Render {key: "value", ...} for MERGE, skipping None values."""
    parts = [f"{k}: {_q(v)}" for k, v in kwargs.items() if v is not None]
    return "{" + ", ".join(parts) + "}"


def emit_cypher(ir: SopIR, linked: LinkedIR, run_id: str) -> str:
    lines: list[str] = [
        f"// Generated by policy-compiler Layer 3  run_id={run_id}",
        f"// SopIR schema_version={ir.schema_version}  review={ir.review_status}",
        "// DO NOT EDIT — regenerate from source.",
        "",
        "// ── Nodes ──────────────────────────────────────────────────────────",
        "",
    ]

    # --- Symbol nodes (sorted for determinism) ---
    for role in sorted(ir.symbols.roles, key=lambda r: r.id):
        lines.append(f"MERGE (:Role {_props(id=role.id, name=role.name)});")
    for art in sorted(ir.symbols.artifacts, key=lambda a: a.id):
        lines.append(f"MERGE (:Artifact {_props(id=art.id, name=art.name)});")
    for sys in sorted(ir.symbols.systems, key=lambda s: s.id):
        lines.append(f"MERGE (:System {_props(id=sys.id, name=sys.name)});")
    for term in sorted(ir.symbols.terms, key=lambda t: t.id):
        lines.append(f"MERGE (:Term {_props(id=term.id, name=term.name)});")

    if ir.symbols.roles or ir.symbols.artifacts or ir.symbols.systems or ir.symbols.terms:
        lines.append("")

    # --- Process / Step / Decision nodes ---
    for proc in sorted(ir.processes, key=lambda p: p.id):
        lines.append(f"MERGE (:Process {_props(id=proc.id, name=proc.name, run_id=run_id)});")
        for step in sorted(proc.steps, key=lambda s: s.id):
            sla_str = None
            if step.sla:
                sla_str = (
                    f"{step.sla.max_duration} {step.sla.unit}"
                    if step.sla.unit
                    else str(step.sla.max_duration)
                )
            step_props = _props(
                id=step.id, action=step.action, modal=str(step.modal or ""), sla=sla_str
            )
            lines.append(f"MERGE (:Step {step_props});")
        for dec in sorted(proc.decisions, key=lambda d: d.id):
            lines.append(f"MERGE (:Decision {_props(id=dec.id, question=dec.question)});")

    # Terminal node (singleton)
    lines.append('MERGE (:Terminal {id: "END"});')
    lines.append("")
    lines.append("// ── Relationships ────────────────────────────────────────────────")
    lines.append("")

    for proc in sorted(ir.processes, key=lambda p: p.id):
        pid = proc.id
        for step in sorted(proc.steps, key=lambda s: s.id):
            sid = step.id
            lines.append(
                f"MERGE (p:Process {{id: {_q(pid)}}})-[:HAS_STEP]->"
                f"(s:Step {{id: {_q(sid)}}});"
            )
            if step.actor_role_id:
                lines.append(
                    f"MERGE (s:Step {{id: {_q(sid)}}})-[:PERFORMED_BY]->"
                    f"(r:Role {{id: {_q(step.actor_role_id)}}});"
                )
            for art_id in sorted(step.inputs):
                lines.append(
                    f"MERGE (s:Step {{id: {_q(sid)}}})-[:CONSUMES]->"
                    f"(a:Artifact {{id: {_q(art_id)}}});"
                )
            for art_id in sorted(step.outputs):
                lines.append(
                    f"MERGE (s:Step {{id: {_q(sid)}}})-[:PRODUCES]->"
                    f"(a:Artifact {{id: {_q(art_id)}}});"
                )
            for sys_id in sorted(step.systems):
                lines.append(
                    f"MERGE (s:Step {{id: {_q(sid)}}})-[:USES]->"
                    f"(sys:System {{id: {_q(sys_id)}}});"
                )
            if step.source_spans:
                quote = step.source_spans[0].quote[:200]
                lines.append(
                    f"MERGE (s:Step {{id: {_q(sid)}}})-[:DERIVED_FROM]->"
                    f"(c:Clause {_props(quote=quote, doc_id=step.source_spans[0].document_id)});"
                )

        for dec in sorted(proc.decisions, key=lambda d: d.id):
            did = dec.id
            lines.append(
                f"MERGE (p:Process {{id: {_q(pid)}}})-[:HAS_DECISION]->"
                f"(d:Decision {{id: {_q(did)}}});"
            )
            if dec.source_spans:
                quote = dec.source_spans[0].quote[:200]
                lines.append(
                    f"MERGE (d:Decision {{id: {_q(did)}}})-[:DERIVED_FROM]->"
                    f"(c:Clause {_props(quote=quote, doc_id=dec.source_spans[0].document_id)});"
                )

        for trans in sorted(proc.transitions, key=lambda t: (t.from_id, t.to_id)):
            from_id, to_id = trans.from_id, trans.to_id
            label_prop = f", label: {_q(trans.label)}" if trans.label else ""
            if to_id == "END":
                lines.append(
                    f"MERGE (n {{id: {_q(from_id)}}})-[:NEXT{{{label_prop.lstrip(', ')}}}]->"
                    f"(:Terminal {{id: \"END\"}});"
                )
            else:
                lines.append(
                    f"MERGE (n {{id: {_q(from_id)}}})-[:NEXT{{{label_prop.lstrip(', ')}}}]->"
                    f"(m {{id: {_q(to_id)}}});"
                )

    lines.append("")
    return "\n".join(lines)


def cypher_sha256(cypher_text: str) -> str:
    return hashlib.sha256(cypher_text.encode()).hexdigest()
